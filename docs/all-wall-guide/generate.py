def wrap(text, font, size, width):
    lines, current = [], ""
    for word in text.split():
        candidate = f"{current} {word}".strip()
        if font.text_length(candidate, fontsize=size) > width and current:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    assert all(font.text_length(line, fontsize=size) <= width + 0.1 for line in lines)
    return lines


def main():
    regular = fitz.Font(fontfile=str(REGULAR))
    bold = fitz.Font(fontfile=str(BOLD))
    doc = fitz.open()

    def new_page(number):
        page = doc.new_page(width=595, height=842)
        page.insert_font(fontname="Guide", fontfile=str(REGULAR))
        page.insert_font(fontname="GuideBold", fontfile=str(BOLD))
        page.insert_text((LEFT, 45), "ALL WALL", fontname="GuideBold", fontsize=20, color=INK)
        page.insert_text((LEFT, 70), "Краткая инструкция пользователя", fontname="Guide", fontsize=14, color=INK)
        page.draw_line((LEFT, 83), (RIGHT, 83), color=GREEN, width=1.5)
        page.insert_text((LEFT, 810), "ALL WALL · Руководство пользователя",
                         fontname="Guide", fontsize=8, color=(0.4, 0.4, 0.4))
        page.insert_text((RIGHT - 45, 810), f"{number} / 2", fontname="Guide", fontsize=8,
                         color=(0.4, 0.4, 0.4))
        return page, 106

    def paragraph(page, y, text, size=BODY_SIZE, leading=LEADING, color=INK):
        for line in wrap(text, regular, size, RIGHT - LEFT):
            assert y <= BOTTOM, f"Page overflow at {line!r}"
            page.insert_text((LEFT, y), line, fontname="Guide", fontsize=size, color=color)
            y += leading
        return y + 3

    def section(page, y, title, paragraphs):
        assert bold.text_length(title, fontsize=13) <= RIGHT - LEFT
        page.insert_text((LEFT, y), title, fontname="GuideBold", fontsize=13, color=GREEN)
        y += 22
        for text in paragraphs:
            y = paragraph(page, y, text)
        return y + 8

    page, y = new_page(1)
    y = paragraph(page, y, "Примерьте стеновые панели на фото интерьера и сформируйте коммерческое предложение (КП).")
